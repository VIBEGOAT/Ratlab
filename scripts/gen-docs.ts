// Generates docs/fidelity-table.md from the fidelity registry so the document cannot drift from the code.
import { writeFileSync } from "node:fs";
import { DISCLAIMER, FIDELITY, SIM_VERSION, listUnverifiedConstants, CONSTANTS, REFERENCES } from "../packages/sim-core/src";

const order = ["MECHANISTIC", "SEMI-QUANTITATIVE", "ILLUSTRATIVE"] as const;
let md = `# Model fidelity table\n\nGenerated by \`npm run gen:docs\` from the fidelity registry (simulator version ${SIM_VERSION}). Do not edit by hand.\n\n> ${DISCLAIMER}\n\n`;
md += `Meaning of the labels:\n\n- **MECHANISTIC**: standard equations or algorithms that can be checked by tests.\n- **SEMI-QUANTITATIVE**: mechanism-shaped, but parameters are assumed or tuned, not fitted to data.\n- **ILLUSTRATIVE**: shows how the pieces connect. No predictive claim.\n\n`;
for (const label of order) {
  const rows = FIDELITY.filter((f) => f.label === label);
  md += `## ${label} (${rows.length})\n\n| Subsystem | Why this label |\n|---|---|\n`;
  for (const r of rows) md += `| ${r.name} | ${r.justification.replace(/\|/g, "/")} |\n`;
  md += "\n";
}
const unverified = listUnverifiedConstants().length;
const refsUnv = REFERENCES.filter((r) => r.status !== "VERIFIED").length;
md += `## Data status\n\n- Constants unverified: ${unverified} of ${Object.keys(CONSTANTS).length} (see \`data/needs-expert-check.md\`).\n- References unverified: ${refsUnv} of ${REFERENCES.length}.\n- All compounds are fictional archetypes.\n`;
writeFileSync(new URL("../docs/fidelity-table.md", import.meta.url), md);
console.log("wrote docs/fidelity-table.md");
