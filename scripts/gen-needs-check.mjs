// Regenerates data/needs-expert-check.md from reference.json and references.json.
import fs from "node:fs";
const root = new URL("../data/", import.meta.url);
const c = JSON.parse(fs.readFileSync(new URL("reference.json", root), "utf8")).constants;
const r = JSON.parse(fs.readFileSync(new URL("references.json", root), "utf8")).references;
const uc = Object.entries(c).filter(([, v]) => v.status !== "VERIFIED");
const ur = r.filter((x) => x.status !== "VERIFIED");
let md = "# Needs expert check\n\nGenerated by `npm run gen:needs`. Do not edit by hand.\n\n";
md += `## Constants not yet verified (${uc.length} of ${Object.keys(c).length})\n\n| Key | Value | Unit | Our confidence | Source | Note |\n|---|---|---|---|---|---|\n`;
for (const [k, v] of uc) md += `| \`${k}\` | ${v.value} | ${v.unit} | ${v.confidence} | ${v.source} | ${(v.note ?? "").replace(/\|/g, "/")} |\n`;
md += `\n## References not yet verified (${ur.length} of ${r.length})\n\n| Id | Citation | Note |\n|---|---|---|\n`;
for (const x of ur) md += `| \`${x.id}\` | ${x.authors} (${x.year ?? "n.d."}). ${x.title}. ${x.venue} | ${(x.note ?? "").replace(/\|/g, "/")} |\n`;
fs.writeFileSync(new URL("needs-expert-check.md", root), md);
console.log(`wrote needs-expert-check.md: ${uc.length} constants, ${ur.length} references`);
