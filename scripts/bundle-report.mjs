// Bundle size report with budgets. Run after a build: npm run bundle
// Writes docs/bundle-report.md and exits 1 if a budget is exceeded.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { join } from "node:path";

const dir = "apps/web/dist/assets";
const BUDGET = {
  entry: 170 * 1024,   // the JavaScript every visitor downloads first, gzipped
  lazy: 260 * 1024,    // any single lazily loaded chunk, gzipped
  css: 12 * 1024,      // all CSS, gzipped
  worker: 120 * 1024,  // the simulation worker, gzipped
};

const files = readdirSync(dir).filter((f) => !f.endsWith(".map")).map((f) => {
  const buf = readFileSync(join(dir, f));
  const kind = f.endsWith(".js") ? (f.startsWith("index-") ? "entry" : /worker/i.test(f) ? "worker" : "lazy") : f.endsWith(".css") ? "css" : f.endsWith(".woff2") ? "font" : "other";
  return { f, kind, raw: buf.length, gz: kind === "font" ? buf.length : gzipSync(buf).length };
}).sort((a, b) => b.gz - a.gz);

// the stylesheet is inlined into index.html at build time; count it (and the page itself) from there
const html = readFileSync("apps/web/dist/index.html", "utf8");
// style rules only: the embedded font (a data: URL) is counted in the page HTML instead
const inlineCss = (html.match(/<style>([\s\S]*?)<\/style>/g) ?? []).join("").replace(/url\(data:[^)]*\)/g, "url()");
files.push({ f: "index.html (page + inlined CSS and Latin font)", kind: "html", raw: Buffer.byteLength(html), gz: gzipSync(html).length });
files.push({ f: "(style rules inside index.html, without the font)", kind: "css", raw: Buffer.byteLength(inlineCss), gz: gzipSync(inlineCss).length });

const sum = (k) => files.filter((x) => x.kind === k).reduce((s, x) => s + x.gz, 0);
const kb = (n) => `${(n / 1024).toFixed(1)} kB`;
const checks = [
  ["Entry JavaScript (gzip)", sum("entry"), BUDGET.entry],
  ["Largest lazy chunk (gzip)", Math.max(0, ...files.filter((x) => x.kind === "lazy").map((x) => x.gz)), BUDGET.lazy],
  ["All CSS (gzip)", sum("css"), BUDGET.css],
  ["Page HTML with inlined CSS and font (gzip)", files.find((x) => x.kind === "html").gz, 60 * 1024],
  ["Simulation worker (gzip)", Math.max(0, ...files.filter((x) => x.kind === "worker").map((x) => x.gz)), BUDGET.worker],
];

const lines = [
  "# Bundle size report",
  "",
  "Generated by `npm run bundle` from the production build. Sizes are gzip, except fonts (already compressed).",
  "",
  "## Budgets",
  "",
  "| Check | Size | Budget | |",
  "|---|---:|---:|---|",
  ...checks.map(([n, v, b]) => `| ${n} | ${kb(v)} | ${kb(b)} | ${v <= b ? "ok" : "OVER"} |`),
  "",
  "The page HTML carries the stylesheet and the Latin Geist font inline, so the first paint needs no other request. The entry chunk is the rest of what loads before the app starts. The 3D engine (three.js, react-three-fiber, post-processing) is a lazy chunk fetched after first paint, the audio engine loads only if sound is switched on, and each Lab view is its own chunk.",
  "",
  "## Every file",
  "",
  "| File | Kind | Raw | Gzip |",
  "|---|---|---:|---:|",
  ...files.map((x) => `| ${x.f} | ${x.kind} | ${kb(x.raw)} | ${kb(x.gz)} |`),
  "",
];
writeFileSync("docs/bundle-report.md", lines.join("\n"));
for (const [n, v, b] of checks) console.log(`${v <= b ? "ok  " : "OVER"} ${n}: ${kb(v)} (budget ${kb(b)})`);
console.log(`${files.length} files, total ${kb(files.reduce((s, x) => s + x.raw, 0))} raw`);
if (checks.some(([, v, b]) => v > b)) process.exit(1);
void statSync;
